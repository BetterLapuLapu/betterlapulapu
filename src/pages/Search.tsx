import Section from '../components/ui/Section';
import Breadcrumbs from '../components/ui/Breadcrumbs';
import { Heading } from '../components/ui/Heading';
import { Text } from '../components/ui/Text';
import SEO from '../components/SEO';
import { Link, useSearchParams } from 'react-router-dom';
import { useEffect, useState } from 'react';
import { useTranslation } from 'react-i18next';

interface PagefindResultData {
  url: string;
  excerpt: string;
  meta: { title?: string; category?: string };
  filters: { section?: string[] };
}

interface Pagefind {
  debouncedSearch: (
    term: string,
    options?: object,
    timeout?: number
  ) => Promise<{
    results: { id: string; data: () => Promise<PagefindResultData> }[];
  } | null>;
}

const MAX_RESULTS = 20;

// Generated by `npm run search:index` into public/pagefind
const pagefindPath = `${import.meta.env.BASE_URL}pagefind/pagefind.js`;
let pagefindPromise: Promise<Pagefind> | null = null;

function loadPagefind(): Promise<Pagefind> {
  // An absolute URL stops the Vite dev server from rewriting the import
  // (it would append ?import and fail to serve the file from /public)
  const pagefindUrl = new URL(pagefindPath, window.location.origin).href;
  pagefindPromise ??= import(/* @vite-ignore */ pagefindUrl);
  return pagefindPromise;
}

export default function Search() {
  const { t } = useTranslation();
  const [searchParams, setSearchParams] = useSearchParams();
  const query = searchParams.get('q') ?? '';
  const [results, setResults] = useState<PagefindResultData[]>([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(false);

  useEffect(() => {
    const term = query.trim();
    if (!term) {
      setResults([]);
      setLoading(false);
      return;
    }

    let cancelled = false;
    setLoading(true);

    loadPagefind()
      .then(pagefind => pagefind.debouncedSearch(term, {}, 200))
      .then(async search => {
        // null means a newer search superseded this one
        if (!search || cancelled) return;
        const data = await Promise.all(
          search.results.slice(0, MAX_RESULTS).map(result => result.data())
        );
        if (cancelled) return;
        setResults(data);
        setError(false);
        setLoading(false);
      })
      .catch(err => {
        if (cancelled) return;
        console.error('Search failed', err);
        setError(true);
        setLoading(false);
      });

    return () => {
      cancelled = true;
    };
  }, [query]);

  const handleChange = (value: string) => {
    setSearchParams(value ? { q: value } : {}, { replace: true });
  };

  return (
    <>
      <SEO
        title={t('common.search')}
        description={t('search.seoDescription', {
          governmentName: import.meta.env.VITE_GOVERNMENT_NAME,
        })}
      />
      <Section>
        <Breadcrumbs />
        <Heading>{t('common.search')}</Heading>
        <Text size="lg" className="max-w-[640px]">
          {t('search.intro')}
        </Text>

        <form
          role="search"
          className="mb-[30px] max-w-[640px] tablet:mb-10"
          onSubmit={e => e.preventDefault()}
        >
          <label htmlFor="search-input" className="type-s mb-[5px] block">
            {t('search.inputLabel')}
          </label>
          <div
            id="search-hint"
            className="type-body mb-[15px] text-ink-secondary"
          >
            {t('search.placeholder')}
          </div>
          <input
            id="search-input"
            type="search"
            aria-describedby="search-hint"
            className="type-body h-10 w-full rounded-none border-2 border-ink px-[5px]"
            value={query}
            onChange={e => handleChange(e.target.value)}
            autoFocus
          />
        </form>

        {error && (
          <div
            role="alert"
            className="mb-[30px] max-w-[640px] border-[5px] border-alert p-[15px] tablet:p-5"
          >
            <p className="type-body">{t('search.unavailable')}</p>
          </div>
        )}

        {!error && query.trim() && !loading && results.length === 0 && (
          <Text>{t('search.noResults', { query: query.trim() })}</Text>
        )}

        {!error && results.length > 0 && (
          <ol
            className="max-w-[640px] border-t border-rule"
            aria-busy={loading}
          >
            {results.map(result => (
              <li key={result.url} className="border-b border-rule py-5">
                <h2 className="type-s mb-2.5">
                  <Link to={result.url} className="link">
                    {result.meta.title}
                  </Link>
                </h2>
                <p
                  className="type-small mb-2.5 [&_mark]:bg-transparent [&_mark]:font-bold [&_mark]:text-ink"
                  dangerouslySetInnerHTML={{ __html: result.excerpt }}
                />
                <p className="type-small text-ink-secondary">
                  {[result.filters.section?.[0], result.meta.category]
                    .filter(Boolean)
                    .join(' · ')}
                </p>
              </li>
            ))}
          </ol>
        )}
      </Section>
    </>
  );
}
